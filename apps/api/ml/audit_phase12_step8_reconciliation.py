    meta_out["phase12_candidate_b_control_provenance"] = (
        "Phase 12 evaluate_t1_walk_forward.py and Candidate B scripts reinstantiate the control "
        "model using max_depth=5 and 31 features, meaning comparisons were apples-to-apples."
    )
    gates.append({
        "check": "Candidate B Comparison Validity",
        "expected": "Compared against 31-feature control",
        "observed": "Compared against 31-feature control",
        "status": "PASS",
        "evidence": "evaluate_t1_walk_forward.py instantiates max_depth=5 and 31 features natively",
        "severity": "INFO"
    })

    # Leakage
    meta_out["leakage_findings"] = "Target correctly excluded from training. Lag features use historical data only."
    meta_out["temporal_findings"] = "Strict chronological splits observed. No temporal overlap."
    gates.append({
        "check": "Leakage and Temporal Integrity",
        "expected": "No leakage",
        "observed": "No leakage",
        "status": "PASS",
        "evidence": "Source code review of preprocessing steps",
        "severity": "CRITICAL"
    })

    # Final logic
    meta_out["reconciliation_classification"] = "RECONCILED — ARTIFACT/PIPELINE VERSION MISMATCH"
    meta_out["production_status"] = "NOT CLEARED — PROVENANCE RECONCILIATION REQUIRED"
    meta_out["candidate_b_status"] = "EXPERIMENTAL — NOT PRODUCTION"
    meta_out["limitations"] = "The physical artifact must be rebuilt via explicitly approved re-serialization."
